// Package resetgen реализует команду reset, которая генерирует метод Reset
// для структур, помеченных комментарием
//
//	// generate:reset
//
// Методы структур одного пакета попадают в файл reset.gen.go этого пакета.
//
// # Запуск
//
//	go run ./cmd/reset
//
// Команду запускают из корня проекта: генератор обходит пакеты ./...
//
// # Правила сброса
//
//	примитивы     нулевое значение: 0, "", false
//	слайсы        обрезаются по длине: s = s[:0]
//	мапы          очищаются: clear(m)
//	указатели     не nil указатель сбрасывает значение по этим правилам
//	типы с Reset  вызывается их Reset
//	структуры и массивы без Reset обнуляются с сохранением исходного типа
//	остальное     nil
package resetgen
